"""
Compile the outputs of `evaluate_detection.py`, `evaluate_mitigation.py`, and `profile_real_latency.py`
into publication-ready Markdown (`PAPER2_RESULTS_SUMMARY.md`) and LaTeX tables (`paper2_tables.tex`).

Usage (after downloading `trueguard_v2_results.zip` from Colab):
  python tools/compile_paper2_tables.py --dir results/v2/TinyLlama__TinyLlama-1.1B-Chat-v1.0
"""
import argparse, json, os, zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def compile_dir(res_dir):
    det_path = os.path.join(res_dir, "detection_report.json")
    mit_path = os.path.join(res_dir, "mitigation", "mitigation_report.json")
    lat_path = os.path.join(res_dir, "real_latency.json")

    det = json.load(open(det_path)) if os.path.exists(det_path) else None
    mit = json.load(open(mit_path)) if os.path.exists(mit_path) else None
    lat = json.load(open(lat_path)) if os.path.exists(lat_path) else None

    md = ["# TRUEGUARD (Paper 2) — Consolidated Experimental Tables & Hypothesis Audit\n"]
    tex = ["% Auto-generated by tools/compile_paper2_tables.py from real experimental JSON outputs\n"]

    if det:
        md.append("## Table 1 — In-Distribution 5-Fold Grouped CV (Detection & Single-Sensor Baselines)\n")
        md.append("| Benchmark | Pairs | TRUEGUARD Fusion AUROC [95% CI] | ISP | AAS | EEM | DST | Best Raw Baseline | $\\Delta$ vs Best Single ($p$) | F1 | ECE |")
        md.append("|---|---:|---|---|---|---|---|---|---|---|---|")

        tex.append("\\begin{table*}[t]\\centering\\caption{In-distribution 5-fold grouped cross-validation AUROC and sensor breakdown.}")
        tex.append("\\begin{tabular}{lrrrrrrrrr}\\toprule")
        tex.append("Benchmark & $N$ & Fusion AUROC (95\\% CI) & ISP & AAS & EEM & DST & Best Raw & $\\Delta_{\\text{best}}$ ($p$) & F1 \\\\\\midrule")

        for name, r in det["datasets"].items():
            f = r["fusion"]; s = r["single_sensor_trained"]; g = r["fusion_vs_best_single"]
            br_k, br_v = max(r["raw_untrained_baselines"].items(), key=lambda kv: kv[1]["auroc"])
            md.append(
                f"| `{name}` | {r['n_questions']} | **{f['auroc']:.3f}** [{f['auroc_ci95'][0]:.3f}, {f['auroc_ci95'][1]:.3f}] "
                f"| {s['ISP']['auroc']:.3f} | {s['AAS']['auroc']:.3f} | {s['EEM']['auroc']:.3f} | {s['DST']['auroc']:.3f} "
                f"| `{br_k}`={br_v['auroc']:.3f} | {g['gain']:+.3f} ({g['p_value']:.2f}) | {f['f1']:.3f} | {f['ece']:.3f} |"
            )
            tex_name = name.replace("_", r"\_")
            tex.append(
                f"{tex_name} & {r['n_questions']} & "
                f"\\textbf{{{f['auroc']:.3f}}} ({f['auroc_ci95'][0]:.3f}--{f['auroc_ci95'][1]:.3f}) & "
                f"{s['ISP']['auroc']:.3f} & {s['AAS']['auroc']:.3f} & {s['EEM']['auroc']:.3f} & {s['DST']['auroc']:.3f} & "
                f"{br_v['auroc']:.3f} & {g['gain']:+.3f} ({g['p_value']:.2f}) & {f['f1']:.3f} \\\\"
            )
        tex.append("\\bottomrule\\end{tabular}\\end{table*}\n")

        md.append("\n## Table 2 — Leave-One-Sensor-Out Ablation\n")
        md.append("| Benchmark | Full (4 Sensors) | $-\\text{ISP}$ | $-\\text{AAS}$ | $-\\text{EEM}$ | $-\\text{DST}$ | Union Recall @ 10% FPR |")
        md.append("|---|---|---|---|---|---|---|")
        for name, r in det["datasets"].items():
            f = r["fusion"]; ab = r["ablation_leave_one_out"]
            ur = r["complementarity_at_10pct_fpr"]["union_recall"]
            md.append(
                f"| `{name}` | **{f['auroc']:.3f}** "
                f"| {ab['without_ISP']['auroc']:.3f} ({ab['without_ISP']['delta_vs_full']:+.3f}) "
                f"| {ab['without_AAS']['auroc']:.3f} ({ab['without_AAS']['delta_vs_full']:+.3f}) "
                f"| {ab['without_EEM']['auroc']:.3f} ({ab['without_EEM']['delta_vs_full']:+.3f}) "
                f"| {ab['without_DST']['auroc']:.3f} ({ab['without_DST']['delta_vs_full']:+.3f}) "
                f"| {ur:.3f} |"
            )

    if mit:
        b = mit["before"]; a = mit["after"]; tc = mit["tier_counts"]; fx = mit["greedy_hallucinations_corrected"]
        md.append("\n## Table 3 — Before-and-After Three-Tier Mitigation on TriviaQA\n")
        md.append(f"- **Model:** `{mit['model']}` (`n_cal={mit['n_cal']}`, `n_test={mit['n_test']}`)")
        md.append(f"- **Calibrated thresholds:** $\\tau_{{\\text{{warning}}}} = {mit['tau_warning']:.3f}$, $\\tau_{{\\text{{fault}}}} = {mit['tau_fault']:.3f}$")
        md.append(f"- **Detection AUROC on model's own TriviaQA generations:** **{mit['test_detection_auroc_on_own_generations']:.3f}**")
        md.append(f"- **Unmitigated hallucination rate:** **{b['hallucination_rate']*100:.1f}%** (accuracy {b['accuracy']*100:.1f}%)")
        md.append(f"- **Post-mitigation hallucination rate among answered queries:** **{a['hallucination_rate_among_answered']*100:.1f}%** "
                  f"(relative drop **{a['relative_hallucination_reduction_among_answered']*100:.1f}%**, coverage **{a['coverage']*100:.1f}%**)")
        md.append(f"- **System-wide hallucination rate (answered & wrong):** **{a['hallucination_rate_system_wide']*100:.1f}%** "
                  f"(relative drop **{a['relative_hallucination_reduction_system_wide']*100:.1f}%**)")
        md.append(f"- **Tier routing counts:** `SAFE={tc['SAFE']}`, `TIER1_RESAMPLE={tc['TIER1_RESAMPLE']}`, "
                  f"`TIER2_RETRIEVAL={tc['TIER2_RETRIEVAL']}`, `TIER3_ABSTAIN={tc['TIER3_ABSTAIN']}`")
        md.append(f"- **Greedy hallucinations actively corrected:** Tier 1 fixed **{fx['by_tier1_resample']}**, Tier 2 fixed **{fx['by_tier2_retrieval']}**")

    if lat:
        md.append("\n## Table 4 — Real Per-Token Latency Profile\n")
        md.append(f"- **Device:** `{lat['device']}` (`{lat['model']}`)")
        md.append(f"- **Vanilla KV-cached decode:** `{lat['vanilla_ms_per_token']:.2f} ms/tok`")
        md.append(f"- **TRUEGUARD online decode:** `{lat['trueguard_online_ms_per_token']:.2f} ms/tok` "
                  f"(sensor + probe math: `{lat['trueguard_sensor_math_only_ms_per_token']:.2f} ms/tok`)")
        md.append(f"- **TRUEGUARD post-pass decode:** `{lat['trueguard_postpass_ms_per_token']:.2f} ms/tok`")
        md.append(f"- **5-sample consistency baseline:** `{lat['multi_sample_5x_ms_per_token']:.2f} ms/tok` "
                  f"(**{lat['speedup_online_vs_5x']:.1f}x speedup** for TRUEGUARD online)")

    md_out = os.path.join(res_dir, "PAPER2_RESULTS_SUMMARY.md")
    tex_out = os.path.join(res_dir, "paper2_tables.tex")
    open(md_out, "w", encoding="utf8").write("\n".join(md) + "\n")
    open(tex_out, "w", encoding="utf8").write("\n".join(tex) + "\n")
    print("wrote", md_out)
    print("wrote", tex_out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(ROOT, "results", "v2", "gpt2"))
    ap.add_argument("--zip", default=None, help="Optional path to trueguard_v2_results.zip from Colab")
    args = ap.parse_args()
    if args.zip and os.path.exists(args.zip):
        with zipfile.ZipFile(args.zip) as zf:
            zf.extractall(ROOT)
    compile_dir(args.dir)
